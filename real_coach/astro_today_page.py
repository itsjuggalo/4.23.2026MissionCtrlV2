#!/usr/bin/env python3
"""astro_today_page.py — renders the live 'today' page for the claudeclaw astrology section
(~/agents/claudeclaw/data/astrology/mike-today-live.html): digest, full read, 30-day timeline, week ahead,
Uranian dial, and the natal+transit wheel (embedded PNG). Regenerated by cron at 08:30 ET (before the 08:32 send links here).
"""
from __future__ import annotations
import base64, html, subprocess, sys
from datetime import datetime
from pathlib import Path
import astro_truth as T

OUT = Path.home() / "agents/claudeclaw/data/astrology/mike-today-live.html"
PY = str(Path.home() / ".venv/bin/python")
RC = Path(__file__).resolve().parent


def run(script: str, *args: str) -> str:
    try:
        r = subprocess.run([PY, str(RC / script), *args], capture_output=True, text=True, timeout=240)
        return (r.stdout or "").strip() or f"({script} printed nothing)"
    except Exception as e:
        return f"({script} unavailable: {e})"


def section(title: str, body: str, open_: bool = False) -> str:
    return (f"<details{' open' if open_ else ''}><summary>{html.escape(title)}</summary>"
            f"<pre>{html.escape(body)}</pre></details>")


def main() -> int:
    now = datetime.now(T.ET)
    wheel = Path.home() / "portfolio/astrology/wheel.png"
    run("astro_wheel.py", "--out", str(wheel))
    img = base64.b64encode(wheel.read_bytes()).decode() if wheel.exists() else ""
    parts = [
        section("Morning digest", "\n".join(ln for ln in run("daily_transits.py").splitlines()
                                             if not ln.startswith("📖 Full read")).rstrip(), True),
        section("Full read (esoteric, sky events, patterns, Uranian dial)", run("daily_transits.py", "--full")),
        section("The Moon — sign & phase against your placements", run("astro_moon.py", "now")),
        section("Your week — themes, exacts (ET), slow transits, progressions", run("astro_weekly.py")),
        section("Next 30 days — timeline (real ephemeris)", run("astro_timeline.py", "30")),
        section("Week ahead — day by day", run("astro_lookahead.py", "week")),
        section("Sky events — lunations, eclipses, stations, retrogrades", run("astro_sky.py", "--days", "60")),
        section("Uranian dial — midpoints & pictures", run("astro_uranian.py", "midpoints")),
        section("Svehla windows", run("svehla.py", "dates")),
        section("Timing — profection & firdaria", run("astro_timing.py", "profection")),
        section("Moon guide — all 12 signs and 8 phases in your chart", run("astro_moon.py", "guide")),
    ]
    parts.insert(2, section("Esoteric read — the soul-level view of your transits", run("astro_esoteric.py")))
    try:
        import astro_lexicon
        parts.append(section("📖 Key — every sign, planet, house and phase (plain + esoteric)",
                             astro_lexicon.esoteric_key(" ".join(astro_lexicon._SIGN_GLYPH) + " " + " ".join(astro_lexicon._KEY_GLYPH)
                                                        + " " + " ".join(f"{h}th house" for h in range(1, 13))
                                                        + " new moon crescent first quarter gibbous full moon disseminating last quarter balsamic")))
    except Exception as e:
        parts.append(section("📖 Key", f"(unavailable: {e})"))
    page = f"""<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Mike · Today's Sky (live)</title>
<style>
body{{margin:0;padding:18px;background:#0b0f1e;color:#e6e4f0;font:15px/1.5 system-ui,-apple-system,Segoe UI,Roboto,sans-serif}}
h1{{font-size:20px;margin:0 0 4px;color:#f5d76e}} .sub{{color:#9a96b8;font-size:13px;margin-bottom:16px}}
details{{background:#121834;border:1px solid #2a3157;border-radius:10px;margin:10px 0;padding:6px 12px}}
summary{{cursor:pointer;font-weight:600;color:#f5d76e;padding:6px 0}}
pre{{white-space:pre-wrap;word-break:break-word;font:14px/1.45 ui-monospace,SFMono-Regular,Menlo,monospace;color:#e6e4f0;margin:6px 0 10px}}
img{{max-width:100%;border-radius:12px;display:block;margin:10px auto}}
.grid{{display:grid;grid-template-columns:1fr;gap:10px}} @media(min-width:1100px){{.grid{{grid-template-columns:1fr 1fr}}}}
</style></head><body>
<h1>Today's sky for Mike</h1>
<div class="sub">Generated {now:%a %b %-d %Y %-I:%M %p} ET · Swiss Ephemeris · Placidus · tropical Western · same engine as the Telegram bot (verified daily 08:25 ET)</div>
{f'<img alt="natal + transit wheel" src="data:image/png;base64,{img}">' if img else ''}
<div class="grid">{''.join(parts)}</div>
</body></html>"""
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(page)
    print(f"wrote {OUT} ({len(page) // 1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
