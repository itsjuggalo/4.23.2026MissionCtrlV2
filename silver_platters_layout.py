def ensure_symlink(src: Path, dst: Path) -> str:
    dst.parent.mkdir(parents=True, exist_ok=True)
    if dst.is_symlink():
        try:
            current = Path(os.readlink(dst))
        except OSError:
            current = None
        if current == src:
            return "noop"
        dst.unlink()
    elif dst.exists():
        return "skipped (existing non-symlink)"
    dst.symlink_to(src)
    return "linked"


