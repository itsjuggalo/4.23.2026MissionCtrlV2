def cmd_setup():
    ROOT.mkdir(parents=True, exist_ok=True)
    ARCHIVE.mkdir(parents=True, exist_ok=True)
    actions = []
    for platter in PLATTERS:
        pdir = ROOT / platter["id"]
        pdir.mkdir(parents=True, exist_ok=True)
        for src_path in platter["files"]:
            src = Path(src_path)
            dst = pdir / src.name
            try:
                action = ensure_symlink(src, dst)
            except Exception as e:
                action = f"error: {type(e).__name__}: {e}"
            actions.append((platter["id"], src.name, action))
    write_readme()
    for pid, name, action in actions:
        print(f"  {pid:30s} {name:35s} {action}")
    print(f"\nWrote {ROOT}/README.md")


def iso_week():
    et_now = datetime.now(timezone.utc).astimezone(ET)
    iso = et_now.isocalendar()
    return f"{iso[0]}-W{iso[1]:02d}"


def cmd_rotate():
    week = iso_week()
    target = ARCHIVE / week
    target.mkdir(parents=True, exist_ok=True)
    actions = []
    for platter in PLATTERS:
        snapshot_dir = target / platter["id"]
        snapshot_dir.mkdir(parents=True, exist_ok=True)
        for src_path in platter["files"]:
            src = Path(src_path)
            if not src.exists():
                actions.append((platter["id"], src.name, "missing, skipped"))
                continue
            dst = snapshot_dir / src.name
            try:
                if src.is_dir():
                    if dst.exists():
                        shutil.rmtree(dst)
                    shutil.copytree(src, dst, symlinks=False)
                else:
                    shutil.copy2(src, dst)
                actions.append((platter["id"], src.name, "snapshot ok"))
            except Exception as e:
                actions.append((platter["id"], src.name, f"error: {type(e).__name__}: {e}"))
    print(f"Rotation snapshot at {target}")
    for pid, name, action in actions:
        print(f"  {pid:30s} {name:35s} {action}")


def cmd_status():
    now_ts = datetime.now(timezone.utc).timestamp()
    for platter in PLATTERS:
        pdir = ROOT / platter["id"]
        print(f"\n{platter['id']} ({platter['domain']})")
        if not pdir.exists():
            print("  (not yet set up, run: silver_platters_layout.py setup)")
            continue
        for src_path in platter["files"]:
            src = Path(src_path)
            label = src.name
            if not src.exists():
                print(f"  {label:35s} MISSING")
                continue
            if src.is_dir():
                children = list(src.glob("*"))
                latest = max((c.stat().st_mtime for c in children), default=0)
                age_min = (now_ts - latest) / 60.0 if latest else None
                print(f"  {label:35s} dir, {len(children)} files, newest {age_min:.1f}min" if age_min else f"  {label:35s} dir, empty")
            else:
                age_min = (now_ts - src.stat().st_mtime) / 60.0
                print(f"  {label:35s} file, {src.stat().st_size} bytes, age {age_min:.1f}min")


def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else "setup"
    if cmd == "setup":
        cmd_setup()
    elif cmd == "rotate":
        cmd_rotate()
    elif cmd == "status":
        cmd_status()
    else:
        print(f"Unknown command: {cmd}. Valid: setup | rotate | status")
        sys.exit(1)


if __name__ == "__main__":
    main()
